import os
import requests

TOKEN = os.getenv("TELEGRAM_BOT_TOKEN")
# Чат редакции с Главредом
CHAT_ID = -5457457789

if not TOKEN:
    print("❌ Не задан TELEGRAM_BOT_TOKEN")
    exit(1)

HELP_TEXT = """📌 **ПУЛЬТ УПРАВЛЕНИЯ РЕДАКЦИЕЙ (ШПАРГАЛКА)**

🚀 **Конвейер и черновики:**
• `Подготовь дайджест` — собрать новости, профильтровать и показать черновик.
• `Поправь [указание]` — точечно изменить черновик (например: *«Поправь: замени ссылку во 2 пункте»*).

📢 **Публикация:**
• `Публикуй` (или `Опубликуй сейчас`) — выложить утвержденный черновик в канал.

🧹 **Очистка и аудит канала:**
• `Почисти канал` (или `Проверь ссылки`) — смысловой аудит по Манифесту и удаление неактуальных акций.
• `Удали за сегодня` — удалить все сегодняшние посты.
• `Удали за 3 дня` — удалить посты за выбранное число дней.
• `Удали все посты` — полная зачистка опубликованных ботом постов.

⏰ **Автоматика по расписанию (cron):**
• **08:30** — бот сам присылает готовый утренний дайджест на согласование.
• **03:00** — ночной аудит ссылок и очистка архива.

💬 **Любой другой вопрос** — Главред ответит и поможет с идеями по Манифесту."""

# 1. Отправляем сообщение в чат
res = requests.post(
    f"https://api.telegram.org/bot{TOKEN}/sendMessage",
    json={"chat_id": CHAT_ID, "text": HELP_TEXT, "parse_mode": "Markdown"}
)

if not res.ok:
    print(f"❌ Ошибка отправки: {res.text}")
    exit(1)

msg_id = res.json().get("result", {}).get("message_id")

# 2. Закрепляем отправленное сообщение в шапке чата
pin_res = requests.post(
    f"https://api.telegram.org/bot{TOKEN}/pinChatMessage",
    json={"chat_id": CHAT_ID, "message_id": msg_id, "disable_notification": True}
)

if pin_res.ok:
    print("✅ Памятка успешно отправлена и закреплена в чате редакции!")
else:
    print(f"⚠️ Сообщение отправлено, но не закрепилось (проверь права бота на закреп): {pin_res.text}")
